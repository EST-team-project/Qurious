export const TERMS_FOOTER = `이 안내는 수업 프로젝트용 초안(${TERMS_VERSION})입니다. 법률 자문이 아니며, 실제 서비스로 운영하기 전에 법률 검토가 필요합니다.`;

/** 한 항목 → HTML. esc 는 화면이 쓰는 이스케이프 함수(내용은 이 파일의 고정 글이지만 습관대로 거친다). */
export function renderTerm(term, esc) {
  const lead = term.lead ? `<p class="terms-lead">${esc(term.lead)}</p>` : "";
  const body = term.clauses.map(c =>
    `<section class="terms-clause"><h4>${esc(c.h)}</h4>${c.b.map(p => `<p>${esc(p)}</p>`).join("")}</section>`).join("");
  return `<article class="terms-term" id="terms-${esc(term.id)}"><h3>${esc(term.title)}</h3>${lead}${body}</article>`;
}

/** 전문 페이지 · 모달 아래에 붙는 글. */
export function renderFooter(esc) {
  return `<p class="terms-foot">${esc(TERMS_FOOTER)}</p>`;
}

/** id → 항목. */
export function termById(id) {
  return TERMS.find(t => t.id === id) || null;
}
