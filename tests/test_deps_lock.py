def test_lock_diff_helper_counts_only_installed_and_matching_platform(tmp_path):
    """TC-DL-09 · test.ps1 첫머리의 「호스트 판 ≠ 잠금 판」 알림(결정 D6)이 쓰는 도우미 — 이 파이썬에 깔린 것만 · 이 플랫폼 표지인 줄만
    세고, 출력은 「LOCKDIFF <수>」 다음 줄마다 「이름 이파이썬판 잠금판」(ASCII · PowerShell 5.1 이 읽는다)."""
