"""의존성 잠금 지킴이 (TC-DL) — 잠금 파일 · Dockerfile · compose 이미지 · 서버 ↔ 클라이언트 판 짝 · Qdrant 문지기 경계.

왜 있나 (2026-10-23 · 의존성 판 관리 · DF-149)
- 예전엔 requirements.txt 36줄이 모두 하한만이라 **빌드한 날의 최신**이 들어왔다. 09-28 빌드에 qdrant-client 1.19.1 이
  들어왔고, 그 판은 1.16.0 에서 없어진 `search` 가 없어 번역 검색이 늘 0건이었다(DF-149). 같은 날 새로 풀면 132개 중 62개가 바뀐다.
- 그래서 판은 requirements.lock(간접 의존까지 정확한 판 · uv 가 만듦)이 정하고, Dockerfile 이 그 잠금으로 깔고, 외부 이미지는
  「판 태그@다이제스트」 로 묶는다(결정 D1 · D2 · D3). 이 시험은 그 꼴이 무너지지 않게 지킨다 — 네트워크 없이 파일만 읽는다.
- 잠금을 고치는 법(새 의존 · 고침 판 받기)은 docs/phase-3/05-deployment/로컬실행안내서.md 「의존성 잠금 · 갱신」.

무엇을 보나
1. 잠금 줄은 모두 정확한 판이고 요구 파일의 이름이 모두 잠금에 있으며, 잠금 판이 요구 범위를 만족한다(빠뜨림 · 어긋남).
2. Dockerfile 은 잠금을 제약으로 깔고 pip check 를 돌리며 바탕 이미지를 다이제스트로 묶는다.
3. compose 의 외부 이미지는 모두 「정확한 판 태그@sha256」 · latest 없음.
4. Qdrant 서버(compose)와 qdrant-client(잠금)는 주 판이 같고 부 판 차가 1 이하(Qdrant 공식 「Upgrades」).
5. Qdrant 클라이언트를 만드는 곳은 문지기(app/lib/vector_db.py) 하나 · qdrant 를 import 하는 앱 모듈은 셋뿐 · 없어진 API 이름이 없다.
6. pytest 는 우리 코드(app. · collector.)가 부른 폐기 API 를 오류로 본다 · 이미지 신선도 판정이 잠금 파일을 본다.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements.lock"
DIGEST = re.compile(r"@sha256:[0-9a-f]{64}$")
# 정확한 판 태그 — 점이 든 판(16.15 · v1.19.1 · 5.18.1-community) 또는 3자리 이상 번호 태그(LEAN 의 17748 꼴).
# 점 없는 짧은 숫자(16 · 8)나 16-alpine 같은 뜨는 태그는 거부한다.
EXACT_TAG = re.compile(r"^(v?\d+\.\d+(\.\d+)?(-[a-z0-9.]+)?|\d{3,})$")


def _req_lines(path: Path):
    """요구 파일의 요구 줄 — `-r 다른파일` 은 따라간다 · 주석 · 옵션 줄은 뺀다."""
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split(" #", 1)[0].split("\t#", 1)[0].strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("-r "):
            yield from _req_lines(path.parent / line[3:].strip())
            continue
        if line.startswith("-"):
            continue
        yield Requirement(line)


def _lock() -> dict[str, tuple[str, str]]:
    """잠금 → {정규화 이름: (판, 표지)} — 같은 이름이 두 번이면 실패(플랫폼마다 다른 판을 두지 않는다)."""
    out: dict[str, tuple[str, str]] = {}
    for raw in LOCK.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        spec, _, marker = line.partition(";")
        name, sep, ver = spec.strip().partition("==")
        assert sep and ver.strip(), f"잠금 줄이 정확한 판(==)이 아니다: {line}"
        key = canonicalize_name(name.split("[", 1)[0])
        assert key not in out, f"잠금에 같은 이름이 두 번: {key}"
        out[key] = (ver.strip(), marker.strip())
    return out


def test_lock_exists_and_pins_everything():
    """TC-DL-01 · 잠금 파일이 있고 모든 줄이 정확한 판이다 · uv 가 만든 머리말(다시 만드는 명령)이 남아 있다."""
    head = LOCK.read_text(encoding="utf-8").splitlines()[:2]
    assert head[0].startswith("# This file was autogenerated by uv"), "잠금은 uv pip compile 로 만든다(손으로 고치지 않는다)"
    assert "uv pip compile requirements-dev.txt --universal --python-version 3.12 -o requirements.lock" in head[1]
    lock = _lock()
    assert len(lock) >= 100   # 런타임 + 시험 + 간접 의존(2026-10-23 = 139줄)


@pytest.mark.parametrize("req_file", ["requirements.txt", "requirements-dev.txt"])
def test_every_requirement_is_locked_within_range(req_file):
    """TC-DL-02 · 요구 파일의 이름이 모두 잠금에 있고, 잠금 판이 그 범위(>= · < 등)를 만족한다 —
    의존을 더하고 잠금을 다시 만들지 않았으면 여기서 깨진다(고치는 법: 로컬실행안내서 「의존성 잠금 · 갱신」)."""
    lock = _lock()
    missing, outside = [], []
    for req in _req_lines(ROOT / req_file):
        key = canonicalize_name(req.name)
        if key not in lock:
            missing.append(req.name)
        elif req.specifier and not req.specifier.contains(lock[key][0], prereleases=True):
            outside.append(f"{req.name}{req.specifier} ↔ 잠금 {lock[key][0]}")
    assert not missing, f"{req_file} 에 있는데 잠금에 없다(uv pip compile 을 다시): {missing}"
    assert not outside, f"잠금 판이 요구 범위 밖: {outside}"


def test_dockerfile_installs_with_lock_and_pins_base():
    """TC-DL-03 · Dockerfile 은 잠금을 제약(-c)으로 깔고 pip check 를 돌린다 · 잠금도 이미지 안에 둔다 · 바탕은 다이제스트로 묶는다."""
    src = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    lines = [ln.strip() for ln in src.splitlines() if ln.strip() and not ln.strip().startswith("#")]
    froms = [ln for ln in lines if ln.startswith("FROM ")]
    assert froms and all(DIGEST.search(f.split()[1]) for f in froms), f"바탕 이미지를 다이제스트로 묶지 않았다: {froms}"
    assert "COPY requirements.txt requirements.lock ./" in lines
    pip = [ln for ln in lines if ln.startswith("RUN pip install")]
    assert pip == ["RUN pip install --no-cache-dir -r requirements.txt -c requirements.lock && pip check"], pip


def _compose_services() -> dict[str, dict]:
    """docker-compose.yml 의 서비스마다 image · build 여부(파일 꼴만 읽는 작은 해석 — yaml 패키지 없이)."""
    services: dict[str, dict] = {}
    cur = None
    in_services = False
    for raw in (ROOT / "docker-compose.yml").read_text(encoding="utf-8").splitlines():
        if raw.startswith("services:"):
            in_services = True
            continue
        if in_services and re.match(r"^\S", raw):
            in_services = False
        if not in_services:
            continue
        m = re.match(r"^  ([a-z][\w-]*):\s*$", raw)
        if m:
            cur = services.setdefault(m.group(1), {"image": None, "build": False})
            continue
        if cur is not None:
            mi = re.match(r"^    image:\s*(\S+)", raw)
            if mi:
                cur["image"] = mi.group(1)
            if re.match(r"^    build:", raw):
                cur["build"] = True
    return services


def test_compose_external_images_pinned_by_tag_and_digest():
    """TC-DL-04 · compose 의 외부 이미지(직접 빌드하지 않는 것)는 모두 「정확한 판 태그@sha256」 — latest · 16-alpine 같은 뜨는 태그 금지.
    (같은 태그가 다시 올라와 내용이 바뀐다 — 10-23 postgres 16.15 · redis 8.10.2 실측)"""
    services = _compose_services()
    external = {k: v["image"] for k, v in services.items() if not v["build"]}
    assert {"postgres", "redis", "neo4j", "qdrant", "ollama", "model-pull"} <= set(external), external
    bad = []
    for name, image in external.items():
        ref, _, digest = (image or "").partition("@")
        tag = ref.rsplit(":", 1)[-1] if ":" in ref else ""
        exact = EXACT_TAG.match(tag)
        if not image or not DIGEST.search("@" + digest) or not exact or "latest" in tag:
            bad.append(f"{name}: {image}")
    assert not bad, "외부 이미지는 「정확한 판 태그@sha256:…」 로 묶는다: " + " · ".join(bad)


