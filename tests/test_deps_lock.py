def _minor(v: str) -> tuple[int, int]:
    rel = Version(v.lstrip("v")).release
    return rel[0], rel[1]


def test_qdrant_server_and_client_minor_within_one():
    """TC-DL-05 · 판 짝 — Qdrant 서버(compose)와 qdrant-client(잠금)는 주 판이 같고 부 판 차가 1 이하(Qdrant 공식: SDK 는
    클러스터와 부 판 1 이내 · 서버 먼저). 클라이언트 자체 검사는 경고만 내고 시험은 경고를 꺼 두어 여기서 본다."""
    image = _compose_services()["qdrant"]["image"]
    server = image.split("@", 1)[0].rsplit(":", 1)[-1]
    client = _lock()["qdrant-client"][0]
    (sm, sn), (cm, cn) = _minor(server), _minor(client)
    assert sm == cm and abs(sn - cn) <= 1, f"Qdrant 서버 {server} ↔ qdrant-client {client} — 부 판 1 이내 · 서버 먼저 올린다"


def _app_py():
    for path in (ROOT / "app").rglob("*.py"):
        if "__pycache__" not in path.parts:
            yield path


REMOVED_CLIENT_METHODS = {   # qdrant-client 1.16.0 이 지운 것(1.19.1 에 없음 · 2026-10-23 실측)
    "search", "search_batch", "search_groups", "recommend", "recommend_batch", "recommend_groups",
    "discover", "discover_batch", "upload_records",
}


def test_qdrant_access_goes_through_the_gateway():
    """TC-DL-06 · Qdrant 문지기 경계 — 클라이언트를 만드는 곳은 app/lib/vector_db.py 하나 · qdrant_client 를 import 하는 앱 모듈은
    문지기 · rag_pipeline · user_docs(LangChain 에 동기 클라이언트를 넘기는 둘)뿐 · 「…client.search(」 처럼 없어진 메서드를 부르지 않는다."""
    allowed_import = {"app/lib/vector_db.py", "app/services/rag_pipeline.py", "app/services/user_docs.py"}
    made, imported, removed = [], [], []
    for path in _app_py():
        rel = path.relative_to(ROOT).as_posix()
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                mods = [a.name for a in node.names] if isinstance(node, ast.Import) else [node.module or ""]
                if any(m == "qdrant_client" or m.startswith("qdrant_client.") for m in mods) and rel not in allowed_import:
                    imported.append(f"{rel}:{node.lineno}")
            if isinstance(node, ast.Call):
                fn = node.func
                name = fn.id if isinstance(fn, ast.Name) else fn.attr if isinstance(fn, ast.Attribute) else ""
                if name in ("QdrantClient", "AsyncQdrantClient") and rel != "app/lib/vector_db.py":
                    made.append(f"{rel}:{node.lineno}")
                if (isinstance(fn, ast.Attribute) and fn.attr in REMOVED_CLIENT_METHODS
                        and isinstance(fn.value, ast.Name) and "client" in fn.value.id.lower()):
                    removed.append(f"{rel}:{node.lineno} {fn.value.id}.{fn.attr}(")
                if any(k.arg == "query_vector" for k in node.keywords):
                    removed.append(f"{rel}:{node.lineno} query_vector=")
    assert not made, f"Qdrant 클라이언트는 app/lib/vector_db.py 에서만 만든다: {made}"
    assert not imported, f"qdrant_client 는 문지기로 부른다(vector_db.models() · 예외): {imported}"
    assert not removed, f"qdrant-client 1.16 에서 없어진 API 를 부른다(query_points 로): {removed}"


