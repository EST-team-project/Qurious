"""논의 스캐너 시험 — 네트워크 없이 고정 응답으로 돈다.

가장 중요한 것은 첫 시험이다. 2026-09-21(S42) 에 "팀원 16세션 무반응"이 계측 오류로
드러났다 — 팀원 답이 **내 댓글 아래 답글**로 달려 있었는데 마지막 댓글만 보고 0 으로 셌다.
이 시험은 그 모양(마지막 댓글은 내 것, 팀원 발언은 답글에만)을 그대로 재현한다.
"""
from __future__ import annotations

from scripts.discussion_scan import 결론표_읽기, 경고, 세기


def _댓글(작성자: str, 시각: str, 답글: list[tuple[str, str]] | None = None) -> dict:
    답글 = 답글 or []
    return {
        "author": {"login": 작성자},
        "createdAt": 시각,
        "replies": {
            "totalCount": len(답글),
            "nodes": [{"author": {"login": a}, "createdAt": t} for a, t in 답글],
        },
    }


def _응답(논의들: list[dict], 총수: int | None = None) -> dict:
    return {"data": {
        "viewer": {"login": "devlee328288"},
        "repository": {"discussions": {
            "totalCount": 총수 if 총수 is not None else len(논의들),
            "nodes": 논의들,
        }},
    }}


def _논의(번호: int, 제목: str, 댓글들: list[dict], 본문: str = "", 댓글총수: int | None = None) -> dict:
    return {
        "number": 번호, "title": 제목, "url": "", "body": 본문, "updatedAt": "",
        "category": {"name": "설계"},
        "comments": {
            "totalCount": 댓글총수 if 댓글총수 is not None else len(댓글들),
            "nodes": 댓글들,
        },
    }


def test_답글로만_달린_팀원_발언을_센다():
    # 마지막 댓글은 제안자 것이고, 팀원 발언은 전부 제안자 댓글 아래 답글이다.
    # "마지막 댓글 작성자"만 보면 0 으로 보이는 바로 그 모양.
    논의 = _논의(13, "[논의] D7 모의투자", [
        _댓글("devlee328288", "2026-09-19T03:32:22Z", 답글=[
            ("rkdalstjr", "2026-09-21T06:26:43Z"),
            ("devlee328288", "2026-09-21T07:05:03Z"),
            ("rkdalstjr", "2026-09-21T08:18:20Z"),
        ]),
    ])
    행들, _ = 세기(_응답([논의]))
    행 = 행들[0]

    assert 행.코드 == "D7"
    assert (행.댓글, 행.답글) == (1, 3)
    assert 행.사람별["rkdalstjr"] == 2
    assert 행.사람별["devlee328288"] == 2
    assert 행.팀원_마지막 == "09-21 17:18"      # UTC 08:18 → KST 17:18


def test_결론표를_읽고_상태를_분류한다():
    본문 = "\n".join([
        "## 7. 결론 — 초안",
        "<!-- 결론표:시작 -->",
        "| 안건 | 결론(초안) | 이동원 | 강민석 | 신장환 | 오준영 | 확정 규칙 | 상태 |",
        "|---|---|:-:|:-:|:-:|:-:|---|---|",
        "| ① 실계좌 | L1 | 제안 | ✅ L1 (09-21) | — | — | 72시간 | 🟢 확정 예정 (09-26 18:00) |",
        "| ② 목적 | P2 | 제안 | ✅ P2 (09-15) | ✅ (09-23) | — | 전원 | ⏳ 전원 찬성 대기 3/4 |",
        "| ③ 실행처 | 로컬 \\| 나중 | 제안 | ✅ (09-21) | — | — | 과반 | ⏸️ 연기 |",
        "| ④ 깨진 행 | 칸이 모자람 |",
        "| ⑤ 표기 | ? | 제안 | — | — | — | ? | 결정 전 |",
        "<!-- 결론표:끝 -->",
        "표 밖의 | 줄은 | 읽지 않는다 |",
    ])
    행들 = 결론표_읽기(본문)
    assert len(행들) == 5
    assert 행들[2]["결론(초안)"] == "로컬 | 나중"       # 이스케이프한 파이프는 글자로
    assert "_깨진행" in 행들[3]

    논의 = _논의(13, "[논의] D7", [], 본문=본문)
    행, = 세기(_응답([논의]))[0]
    assert 행.상태_집계 == {"확정 예정": 1, "대기": 1, "연기": 1, "깨진행": 1, "미분류": 1}


def test_마크다운으로_다시_낼_때_파이프를_이스케이프한다(capsys):
    from datetime import datetime

    from scripts.discussion_scan import KST, 마크다운_출력

    본문 = "\n".join([
        "<!-- 결론표:시작 -->",
        "| 안건 | 결론(초안) | 이동원 | 강민석 | 신장환 | 오준영 | 확정 규칙 | 상태 |",
        "|---|---|:-:|:-:|:-:|:-:|---|---|",
        "| ③ 실행처 | 로컬 \\| 나중 | 제안 | — | — | — | 과반 | ⏸️ 연기 |",
        "<!-- 결론표:끝 -->",
    ])
    행들, 메타 = 세기(_응답([_논의(10, "[논의] D2", [], 본문=본문)]))
    지금 = datetime(2026, 9, 23, 12, 0, tzinfo=KST)
    마크다운_출력(행들, 메타, datetime(2026, 9, 27, 23, 59, tzinfo=KST), 지금)
    출력 = capsys.readouterr().out
    assert "| #10 D2 | ③ 실행처 | 로컬 \\| 나중 | ⏸️ 연기 |" in 출력


def test_결론표가_없으면_빈_목록():
    assert 결론표_읽기("## 7. 결론 (결정 후 댓글로 남깁니다)\n\n- [ ] 파생 작업") == []


def test_팀원이_전부_0이면_조회를_의심하라고_경고한다():
    논의 = _논의(6, "[논의] D0", [_댓글("devlee328288", "2026-09-15T00:00:00Z")])
    행들, 메타 = 세기(_응답([논의]))
    알림 = 경고(행들, 메타)
    assert any("조회" in 줄 and "0건" in 줄 for 줄 in 알림)


def test_잘린_응답은_잘렸다고_말한다():
    논의 = _논의(7, "[논의] D1", [_댓글("rkdalstjr", "2026-09-15T00:00:00Z")], 댓글총수=140)
    행들, 메타 = 세기(_응답([논의], 총수=60))
    알림 = 경고(행들, 메타)
    assert any("#7" in 줄 and "1/140" in 줄 for 줄 in 알림)
    assert any("논의 목록이 잘렸다" in 줄 for 줄 in 알림)
